#!/usr/bin/env node
// Regenerates src/lib/supabase/database.types.ts from the linked project via the
// Supabase Management API (same output as `supabase gen types typescript`).
// Needs SUPABASE_PROJECT_REF and SUPABASE_ACCESS_TOKEN in .env.local.
import { writeFileSync } from "node:fs";

process.loadEnvFile?.(".env.local");
const { SUPABASE_PROJECT_REF: ref, SUPABASE_ACCESS_TOKEN: token } = process.env;
if (!ref || !token) {
  console.error("Set SUPABASE_PROJECT_REF and SUPABASE_ACCESS_TOKEN in .env.local");
  process.exit(1);
}
const res = await fetch(`https://api.supabase.com/v1/projects/${ref}/types/typescript?included_schemas=public`, {
  headers: { Authorization: `Bearer ${token}` },
});
if (!res.ok) throw new Error(`HTTP ${res.status}: ${await res.text()}`);
const { types } = await res.json();
const header = "// Generated by `npm run db:types` from the linked Supabase project. Do not edit by hand.\n\n";
writeFileSync("src/lib/supabase/database.types.ts", header + types);
console.log("Wrote src/lib/supabase/database.types.ts");
