import { checkLessonForPublish } from "../blocks/schema.ts";
import type { SeedCourse, SeedTool } from "./data.ts";

const lit = (v: string | null) => (v === null ? "null" : `'${v.replaceAll("'", "''")}'`);
const arr = (v: (string | number)[], type: "text" | "smallint") =>
  `array[${v.map((x) => (typeof x === "number" ? String(x) : lit(x))).join(", ")}]::${type}[]`;
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;

/** Validates every lesson and returns idempotent SQL. Throws on invalid content. */
export function seedToSql(tools: SeedTool[], courses: SeedCourse[]): string {
  const out: string[] = [
    "-- GENERATED by `npm run db:seed:gen` from src/content/seed/data.ts — do not edit.",
    "-- Idempotent: safe to run repeatedly. Published versions are immutable, so changed",
    "-- lesson content is only picked up on a fresh database (or bump version ids).",
    "begin;",
  ];

  for (const t of tools) {
    out.push(
      `insert into public.external_tools (id, slug, name, description, logo_url, base_url, submission_domains, min_age, requires_account, enabled)
values (${lit(t.id)}, ${lit(t.slug)}, ${lit(t.name)}, ${lit(t.description)}, ${lit(t.logo_url)}, ${lit(t.base_url)}, ${arr(t.submission_domains, "text")}, ${t.min_age}, ${t.requires_account}, ${t.enabled})
on conflict (id) do update set slug = excluded.slug, name = excluded.name, description = excluded.description,
  logo_url = excluded.logo_url, base_url = excluded.base_url, submission_domains = excluded.submission_domains,
  min_age = excluded.min_age, requires_account = excluded.requires_account;`,
    );
  }

  for (const c of courses) {
    out.push(
      `insert into public.courses (id, slug, title, subtitle, description, outcomes, course_type, class_levels, subject, cover_image_path, is_free, price_paise, status, published_at)
values (${lit(c.id)}, ${lit(c.slug)}, ${lit(c.title)}, ${lit(c.subtitle)}, ${lit(c.description)}, ${arr(c.outcomes, "text")}, '${c.course_type}', ${arr(c.class_levels, "smallint")}, ${lit(c.subject)}, ${lit(c.cover_image_path)}, ${c.is_free}, ${c.price_paise}, 'published', now())
on conflict (id) do update set slug = excluded.slug, title = excluded.title, subtitle = excluded.subtitle,
  description = excluded.description, outcomes = excluded.outcomes, course_type = excluded.course_type,
  class_levels = excluded.class_levels, subject = excluded.subject, cover_image_path = excluded.cover_image_path,
  is_free = excluded.is_free, price_paise = excluded.price_paise;`,
    );
    c.modules.forEach((m, mi) => {
      out.push(
        `insert into public.modules (id, course_id, title, description, position)
values (${lit(m.id)}, ${lit(c.id)}, ${lit(m.title)}, ${lit(m.description)}, ${mi + 1})
on conflict (id) do update set title = excluded.title, description = excluded.description, position = excluded.position;`,
      );
      m.lessons.forEach((l, li) => {
        const check = checkLessonForPublish(l.blocks);
        if (!check.ok) {
          throw new Error(`Seed lesson "${c.slug}/${l.slug}" is invalid:\n${JSON.stringify(check.issues, null, 2)}`);
        }
        out.push(
          `insert into public.lessons (id, module_id, slug, title, summary, position, estimated_minutes, is_preview)
values (${lit(l.id)}, ${lit(m.id)}, ${lit(l.slug)}, ${lit(l.title)}, ${lit(l.summary)}, ${li + 1}, ${l.estimated_minutes}, ${Boolean(l.is_preview)})
on conflict (id) do update set module_id = excluded.module_id, slug = excluded.slug, title = excluded.title,
  summary = excluded.summary, position = excluded.position, estimated_minutes = excluded.estimated_minutes,
  is_preview = excluded.is_preview;`,
          `insert into public.lesson_versions (id, lesson_id, status, version, blocks, published_at)
values (${lit(l.version_id)}, ${lit(l.id)}, 'published', 1, ${json(check.blocks)}, now())
on conflict (id) do nothing;`,
          `update public.lessons set published_version_id = ${lit(l.version_id)} where id = ${lit(l.id)} and published_version_id is null;`,
        );
      });
    });
  }
  out.push("commit;", "");
  return out.join("\n\n");
}
