import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import { amountInWords, formatPaise } from "@/lib/payments/money";

export type InvoiceForPdf = {
  number: string;
  kind: "invoice" | "credit_note";
  issued_at: string;
  buyer_name: string;
  buyer_email: string;
  student_name: string | null;
  line_items: { description: string; sac?: string; quantity?: number; list_price_paise?: number; discount_paise?: number; amount_paise: number }[];
  taxable_paise: number;
  cgst_paise: number;
  sgst_paise: number;
  igst_paise: number;
  total_paise: number;
  tax_snapshot: {
    mode?: string;
    rate_percent?: number;
    seller_name?: string;
    seller_address?: string;
    seller_gstin?: string | null;
    seller_email?: string;
    sac_code?: string;
    footer?: string;
  };
  provider_payment_id: string | null;
  is_test: boolean;
  original_number?: string | null;
};

/** Standard PDF fonts only cover Latin-1: replace anything else (₹ → "Rs."). */
export function pdfSafe(s: string | null | undefined): string {
  return (s ?? "").replace(/₹/g, "Rs.").replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[–—]/g, "-").replace(/[^\x20-\x7E\xA0-\xFF]/g, "?");
}

const INK = rgb(0.12, 0.16, 0.23);
const MUTED = rgb(0.4, 0.45, 0.52);
const LINE = rgb(0.85, 0.87, 0.9);

export async function renderInvoicePdf(inv: InvoiceForPdf): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const page = doc.addPage([595.28, 841.89]); // A4
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const s = inv.tax_snapshot;
  const registered = Boolean(s.seller_gstin);
  const title = inv.kind === "credit_note" ? "CREDIT NOTE" : registered ? "TAX INVOICE" : "INVOICE";
  doc.setTitle(`${title} ${inv.number}`);
  doc.setAuthor(pdfSafe(s.seller_name));
  doc.setCreator("AI Learning Hub");

  const W = 595.28;
  const M = 48;
  let y = 790;
  const text = (t: string, x: number, yy: number, opts: { f?: PDFFont; size?: number; color?: ReturnType<typeof rgb> } = {}) =>
    page.drawText(pdfSafe(t), { x, y: yy, font: opts.f ?? font, size: opts.size ?? 10, color: opts.color ?? INK });
  const right = (t: string, xr: number, yy: number, opts: { f?: PDFFont; size?: number } = {}) => {
    const f = opts.f ?? font;
    const size = opts.size ?? 10;
    page.drawText(pdfSafe(t), { x: xr - f.widthOfTextAtSize(pdfSafe(t), size), y: yy, font: f, size, color: INK });
  };
  const rule = (yy: number) => page.drawLine({ start: { x: M, y: yy }, end: { x: W - M, y: yy }, thickness: 0.8, color: LINE });

  if (inv.is_test) {
    page.drawRectangle({ x: M, y: y - 4, width: W - 2 * M, height: 22, color: rgb(1, 0.93, 0.8) });
    text("TEST DOCUMENT - generated by the mock payment gateway. Not a real invoice.", M + 8, y + 3, { f: bold, size: 9 });
    y -= 34;
  }

  text(title, M, y, { f: bold, size: 20 });
  right(inv.number, W - M, y + 4, { f: bold, size: 11 });
  right(`Date: ${new Date(inv.issued_at).toLocaleDateString("en-IN", { timeZone: "Asia/Kolkata", day: "2-digit", month: "short", year: "numeric" })}`, W - M, y - 12);
  y -= 34;

  text(s.seller_name ?? "", M, y, { f: bold, size: 11 });
  y = wrap(page, font, s.seller_address ?? "", M, y - 14, 260, 9);
  if (s.seller_gstin) {
    text(`GSTIN: ${s.seller_gstin}`, M, y - 2, { size: 9 });
    y -= 12;
  }
  if (s.seller_email) {
    text(s.seller_email, M, y - 2, { size: 9, color: MUTED });
    y -= 12;
  }

  let by = 790 - (inv.is_test ? 68 : 34) - 0;
  text("Bill to", 330, by, { f: bold, size: 9, color: MUTED });
  text(inv.buyer_name, 330, by - 14, { f: bold });
  text(inv.buyer_email, 330, by - 28, { size: 9 });
  by -= 42;
  if (inv.student_name) {
    text(`Student: ${inv.student_name}`, 330, by, { size: 9 });
    by -= 14;
  }
  if (inv.original_number) {
    text(`Against invoice: ${inv.original_number}`, 330, by, { size: 9 });
    by -= 14;
  }
  y = Math.min(y, by) - 24;

  // Line items
  rule(y + 14);
  text("Description", M, y, { f: bold, size: 9 });
  text("SAC", 330, y, { f: bold, size: 9 });
  right("Qty", 420, y, { f: bold, size: 9 });
  right("Amount (INR)", W - M, y, { f: bold, size: 9 });
  y -= 8;
  rule(y);
  y -= 16;
  for (const li of inv.line_items) {
    const startY = y;
    y = wrap(page, font, li.description, M, y, 270, 10);
    text(li.sac ?? s.sac_code ?? "", 330, startY);
    right(String(li.quantity ?? 1), 420, startY);
    right(formatPaise(li.list_price_paise ?? li.amount_paise), W - M, startY);
    if (li.discount_paise) {
      y -= 2;
      text("Discount", M + 12, y, { size: 9, color: MUTED });
      right(`-${formatPaise(li.discount_paise)}`, W - M, y, { size: 9 });
      y -= 12;
    }
    y -= 6;
  }
  rule(y + 6);
  y -= 12;

  const rate = s.rate_percent ?? 0;
  const rows: [string, number][] = [];
  if (s.mode === "cgst_sgst") rows.push(["Taxable value", inv.taxable_paise], [`CGST @ ${rate / 2}%`, inv.cgst_paise], [`SGST @ ${rate / 2}%`, inv.sgst_paise]);
  else if (s.mode === "igst") rows.push(["Taxable value", inv.taxable_paise], [`IGST @ ${rate}%`, inv.igst_paise]);
  for (const [label, v] of rows) {
    right(label, 440, y, { size: 10 });
    right(formatPaise(v), W - M, y);
    y -= 16;
  }
  right(inv.kind === "credit_note" ? "Total credited" : "Total", 440, y, { f: bold, size: 12 });
  right(`INR ${formatPaise(inv.total_paise)}`, W - M, y, { f: bold, size: 12 });
  y -= 24;
  y = wrap(page, font, amountInWords(inv.total_paise), M, y, W - 2 * M, 9);
  y -= 10;

  if (!registered) {
    text("Supplier not registered under GST; no GST charged.", M, y, { size: 9, color: MUTED });
    y -= 14;
  }
  if (inv.provider_payment_id) {
    text(`Payment reference: ${inv.provider_payment_id}`, M, y, { size: 9, color: MUTED });
    y -= 14;
  }
  if (s.footer) wrap(page, font, s.footer, M, 60, W - 2 * M, 8);

  return doc.save();
}

/** Draws wrapped text; returns the y after the last line. */
function wrap(page: PDFPage, font: PDFFont, input: string, x: number, y: number, width: number, size: number): number {
  const words = pdfSafe(input).split(/\s+/).filter(Boolean);
  let line = "";
  for (const w of words) {
    const next = line ? `${line} ${w}` : w;
    if (font.widthOfTextAtSize(next, size) > width && line) {
      page.drawText(line, { x, y, font, size, color: INK });
      y -= size + 4;
      line = w;
    } else line = next;
  }
  if (line) {
    page.drawText(line, { x, y, font, size, color: INK });
    y -= size + 4;
  }
  return y;
}
